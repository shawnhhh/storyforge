import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { chapterBody, expectChapterReady } from './editor-helpers.js'

test('downloads all formats, verifies backups, confirms restore twice and preserves an old window draft', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: '创建小说', exact: true }).first().click()
  await page.getByRole('dialog').getByLabel('小说名称').fill('中文导出/恢复🌕')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '创建第一章' }).click()
  const body = await expectChapterReady(page, '第 1 章')
  await page.getByRole('textbox', { name: '章节标题' }).fill('初见')
  await body.fill('备份中的中文正文 <&> 🌕')
  await expect(page.locator('.save-status')).toHaveText('已保存到数据库')
  await page.getByRole('button', { name: '添加章节' }).click()
  await expectChapterReady(page, '第 2 章')
  await page.getByRole('textbox', { name: '章节标题' }).fill('远航')
  await expect(page.locator('.save-status')).toHaveText('已保存到数据库')
  await page.getByRole('button', { name: '上移 远航', exact: true }).click()
  await expect(page.locator('.chapter-select').first()).toContainText('远航')
  for (const format of ['markdown', 'txt', 'json']) {
    await page.getByLabel('小说导出格式').selectOption(format)
    const downloaded = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出小说', exact: true }).click()
    const download = await downloaded
    expect(download.suggestedFilename()).toBe(`中文导出_恢复🌕.${format === 'markdown' ? 'md' : format}`)
    const text = readFileSync((await download.path())!, 'utf8')
    if (format === 'json') {
      const exported = JSON.parse(text)
      expect(exported.chapters.map((row: { title: string }) => row.title)).toEqual(['远航', '初见'])
      expect(exported.chapters[1].content.content[0].content[0].text).toBe('备份中的中文正文 <&> 🌕')
    } else expect(text.indexOf('远航')).toBeLessThan(text.indexOf('初见'))
  }
  const other = await context.newPage()
  await other.goto('/')
  await other.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: '中文导出/恢复🌕' }).click()
  // A chapter list can paint while the lazy editor for the first chapter is
  // still mounting. Wait for the initial chapter identity before navigating.
  await expectChapterReady(other, '远航')
  await other.locator('.chapter-select').filter({ hasText: '初见' }).click()
  await expectChapterReady(other, '初见', '备份中的中文正文 <&> 🌕')
  await page.getByRole('button', { name: '备份与恢复', exact: true }).click()
  await page.getByRole('button', { name: '手动备份', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('备份创建成功')
  const manual = page.locator('.backup-list li').filter({ hasText: '手动备份' }).first()
  await manual.getByRole('button', { name: '检查完整性' }).click()
  await expect(page.getByRole('status')).toContainText('完整性检查通过')
  await page.getByRole('button', { name: '返回写作', exact: true }).click()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: '中文导出/恢复🌕' }).click()
  await expectChapterReady(page, '远航')
  await page.locator('.chapter-select').filter({ hasText: '初见' }).click()
  await expectChapterReady(page, '初见', '备份中的中文正文 <&> 🌕')
  await body.fill('备份之后的正文')
  await expect(page.locator('.save-status')).toHaveText('已保存到数据库')
  await page.getByRole('button', { name: '备份与恢复', exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await manual.getByRole('button', { name: '恢复此备份' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await manual.getByRole('button', { name: '恢复此备份' }).click()
  const confirmation = page.getByRole('dialog')
  await expect(confirmation.getByRole('button', { name: '确认恢复' })).toBeDisabled()
  await confirmation.getByLabel('请输入「替换当前全部数据」').fill('替换当前全部数据')
  await confirmation.getByRole('button', { name: '确认恢复' }).click()
  await expect(page.getByRole('status')).toContainText('恢复成功')
  await expect(page.locator('.backup-list')).toContainText('恢复前安全备份')
  await chapterBody(other).fill('旧窗口未保存草稿')
  await expect(other.locator('.save-status')).toHaveText('版本冲突 · 未保存')
  await expect(other.getByRole('textbox', { name: '小说正文' })).toHaveText('旧窗口未保存草稿')
  await page.getByRole('button', { name: '重新加载工作台' }).click()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: '中文导出/恢复🌕' }).click()
  await expectChapterReady(page, '远航')
  await page.locator('.chapter-select').filter({ hasText: '初见' }).click()
  await page.getByText('查看草稿内容与版本信息', { exact: true }).click()
  await expect(page.locator('.draft-recovery pre')).toContainText('旧窗口未保存草稿')
  const recoveredDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出此草稿', exact: true }).click()
  const protectedDraft = JSON.parse(readFileSync((await (await recoveredDownload).path())!, 'utf8'))
  expect(protectedDraft.value.content.content[0].content[0].text).toBe('旧窗口未保存草稿')
  await page.getByRole('button', { name: '保留数据库版本', exact: true }).click()
  await expect(chapterBody(other)).toHaveText('旧窗口未保存草稿')
  await expectChapterReady(page, '初见', '备份中的中文正文 <&> 🌕')
  expect(errors).toEqual([])
  await other.close({ runBeforeUnload: false })
})
