test('profile conflicts retain exportable drafts, guard navigation and require explicit reload', async ({ page, context }) => {
  await novel(page, '双窗口人物冲突')
  await module(page, '人物档案')
  await page.getByRole('button', { name: '新增人物', exact: true }).first().click()
  await page.getByLabel('姓名', { exact: true }).fill('初始人物')
  await saved(page)
  const other = await context.newPage()
  await other.goto('/')
  await other.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: '双窗口人物冲突' }).click()
  await module(other, '人物档案')
  await expect(other.getByLabel('姓名', { exact: true })).toHaveValue('初始人物')
  // Loading the form value precedes its asynchronous protected-draft check.
  // Finish that check before the other window creates the conflicting revision.
  await expect(other.getByLabel('姓名', { exact: true })).toBeEditable()
  await expect(other.locator('.draft-recovery')).toHaveCount(0)
  await page.getByLabel('姓名', { exact: true }).fill('远端已保存')
  await saved(page)
  await other.getByLabel('姓名', { exact: true }).fill('本地冲突草稿🌕')
  await expect(other.locator('.profile-save-status')).toHaveText('版本冲突 · 未保存')
  await expect(other.getByRole('navigation', { name: '小说工作台模块' }).getByRole('button', { name: '世界观', exact: true })).toBeDisabled()
  await expect(other.getByRole('button', { name: '备份与恢复', exact: true })).toBeDisabled()
  await expect(other.getByLabel('姓名', { exact: true })).toHaveValue('本地冲突草稿🌕')
  const downloading = other.waitForEvent('download')
  await other.getByRole('button', { name: '导出资料草稿', exact: true }).click()
  const downloaded = await downloading
  expect(JSON.parse(readFileSync((await downloaded.path())!, 'utf8')).name).toBe('本地冲突草稿🌕')
  other.once('dialog', dialog => dialog.dismiss())
  await other.getByRole('button', { name: '重新加载资料', exact: true }).click()
  await expect(other.getByLabel('姓名', { exact: true })).toHaveValue('本地冲突草稿🌕')
  other.once('dialog', dialog => dialog.accept())
  await other.getByRole('button', { name: '重新加载资料', exact: true }).click()
  await other.getByRole('button', { name: '保留数据库版本', exact: true }).click()
  await expect(other.getByLabel('姓名', { exact: true })).toHaveValue('远端已保存')
  await saved(other)
  // A remote deletion must preserve, rather than recreate, the stale editor's draft.
  page.once('dialog', dialog => dialog.accept())
  await openDeleteMenu(page, '删除人物')
  await page.getByRole('button', { name: '删除人物', exact: true }).click()
  await other.getByLabel('姓名', { exact: true }).fill('被删除后的草稿')
  await expect(other.locator('.profile-save-status')).toHaveText('版本冲突 · 未保存')
  await expect(other.getByLabel('姓名', { exact: true })).toHaveValue('被删除后的草稿')
  await other.close({ runBeforeUnload: false })
})

test('world save failures preserve drafts, invalid input blocks writes and retry works at a narrow viewport', async ({ page }) => {
  await page.setViewportSize({ width: 700, height: 900 })
  await novel(page, '设定重试验收')
  await module(page, '世界观')
  await page.getByRole('button', { name: '新增设定', exact: true }).first().click()
  await page.getByLabel('设定名称', { exact: true }).fill('')
  await expect(page.locator('.profile-save-status')).toHaveText('保存失败')
  await expect(page.getByRole('button', { name: '新增设定', exact: true }).first()).toBeDisabled()
  await page.getByLabel('设定名称', { exact: true }).fill('月宫')
  await saved(page)
  await page.route('**/api/novels/*/world/*', route => route.request().method() === 'PUT' ? route.abort('failed') : route.continue())
  await page.getByLabel('设定内容', { exact: true }).fill('离线仍保留的设定内容 🌕')
  await expect(page.locator('.profile-save-status')).toHaveText('保存失败')
  await expect(page.getByLabel('设定内容', { exact: true })).toHaveValue('离线仍保留的设定内容 🌕')
  await page.unroute('**/api/novels/*/world/*')
  await page.getByRole('button', { name: '重试保存', exact: true }).click()
  await saved(page)
  await page.getByLabel('时间线顺序', { exact: true }).fill('')
  await expect(page.locator('.profile-save-status')).toHaveText('保存失败')
  await page.getByLabel('时间线顺序', { exact: true }).fill('20')
  await saved(page)
  await page.getByRole('button', { name: '刷新资料', exact: true }).click()
  await expect(page.getByLabel('设定内容', { exact: true })).toHaveValue('离线仍保留的设定内容 🌕')
  for (const width of [1440, 1024, 700, 390]) {
    await page.setViewportSize({ width, height: 900 })
    const layout = await page.evaluate(() => ({
      width: window.innerWidth,
      scroll: document.documentElement.scrollWidth,
      overflowing: [...document.querySelectorAll('body *')].filter(element => element.getBoundingClientRect().right > window.innerWidth + 1).slice(0, 8).map(element => ({ tag: element.tagName, class: element.className, right: element.getBoundingClientRect().right })),
    }))
    expect(layout.scroll, JSON.stringify(layout)).toBeLessThanOrEqual(layout.width)
  }
})

test('Chinese composition pauses browser autosave and saves the committed text after compositionend', async ({ page }) => {
  await novel(page, '中文输入法保存')
  await module(page, '人物档案')
  await page.getByRole('button', { name: '新增人物', exact: true }).first().click()
  const name = page.getByLabel('姓名', { exact: true })
  await expect(name).toBeEditable()
  let writes = 0
  page.on('request', request => { if (request.method() === 'PUT' && /\/characters\//.test(request.url())) writes++ })
  await name.focus()
  await name.dispatchEvent('compositionstart', { data: '' })
  await updateComposition(name, 'lin')
  // Intentionally span the 700ms debounce: no intermediate IME text may write.
  await page.waitForTimeout(900)
  expect(writes).toBe(0)
  await expect(page.locator('.profile-save-status')).toHaveText('等待保存…')
  await updateComposition(name, '林月🌕')
  await name.dispatchEvent('compositionend', { data: '林月🌕' })
  await saved(page)
  expect(writes).toBe(1)
  await page.getByRole('button', { name: '刷新资料', exact: true }).click()
  await expect(name).toHaveValue('林月🌕')
})
