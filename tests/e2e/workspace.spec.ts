import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

const body = (page: Page) => page.getByRole('textbox', { name: '小说正文' })
const saved = (page: Page) => expect(page.locator('.save-status')).toHaveText('已保存到数据库')
const browserErrors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const errors: string[] = []
  browserErrors.set(page, errors)
  page.on('pageerror', error => { errors.push(error.message) })
})
test.afterEach(({ page }) => {
  expect(browserErrors.get(page), 'No unhandled browser exceptions').toEqual([])
})
async function createNovel(page: Page, title: string) {
  await page.goto('/')
  await page.getByRole('button', { name: '创建小说', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('小说名称').fill(title)
  await dialog.getByLabel('简介').fill('自动化测试虚构内容')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(title)
}
async function selectNovel(page: Page, title: string) {
  await page.goto('/')
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: title }).click()
  await expect(body(page)).toBeVisible()
}

test('novel settings, chapter ordering, rich text autosave, reload and confirmed deletion', async ({ page }) => {
  await createNovel(page, '端到端创作流程')
  await page.getByRole('button', { name: '小说设置' }).click()
  await page.getByRole('dialog').getByLabel('小说名称').fill('端到端创作流程（修改）')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('端到端创作流程（修改）')
  await page.getByRole('button', { name: '创建第一章' }).click()
  await page.getByRole('textbox', { name: '章节标题' }).fill('起点')
  await body(page).fill('第一段测试故事')
  await expect(page.getByRole('button', { name: '添加章节' })).toBeDisabled()
  await body(page).press('ControlOrMeta+a')
  await page.getByRole('button', { name: '粗体', exact: true }).click()
  await expect(page.getByRole('button', { name: '粗体', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await saved(page)
  await expect(body(page).locator('strong')).toHaveText('第一段测试故事')
  await expect(page.locator('.editor-footer')).toContainText('7 字')
  await page.getByRole('button', { name: '专注写作' }).click()
  await expect(page.getByRole('navigation', { name: '小说列表' })).not.toBeVisible()
  await expect(body(page)).toBeVisible()
  if (process.env.E2E_SCREENSHOT) await page.screenshot({ path: process.env.E2E_SCREENSHOT })
  await page.getByRole('button', { name: '退出专注' }).click()
  await page.getByRole('button', { name: '添加章节' }).click()
  await expect(page.getByRole('textbox', { name: '章节标题' })).toHaveValue('第 2 章')
  await page.getByRole('textbox', { name: '章节标题' }).fill('远航')
  await saved(page)
  await page.getByRole('button', { name: '上移 远航', exact: true }).click()
  await expect(page.locator('.chapter-select').first()).toContainText('远航')
  await selectNovel(page, '端到端创作流程（修改）')
  await expect(page.getByRole('textbox', { name: '章节标题' })).toHaveValue('远航')
  await page.locator('.chapter-select').filter({ hasText: '起点' }).click()
  await expect(body(page).locator('strong')).toHaveText('第一段测试故事')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '删除当前章节' }).click()
  await expect(page.locator('.chapter-select')).toHaveCount(2)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除当前章节' }).click()
  await expect(page.locator('.chapter-select')).toHaveCount(1)
  await expect(page.getByRole('textbox', { name: '章节标题' })).toHaveValue('远航')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除小说', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('创作工作台')
  await expect(page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: '端到端创作流程' })).toHaveCount(0)
})

test('two pages preserve conflicting drafts, export them and recover from remote chapter and novel deletion', async ({ page, context }) => {
  await createNovel(page, '双窗口冲突测试')
  await page.getByRole('button', { name: '创建第一章' }).click()
  await expect(body(page)).toBeVisible()
  const other = await context.newPage()
  await selectNovel(other, '双窗口冲突测试')
  await body(page).fill('窗口一正式正文')
  await saved(page)
  await body(other).fill('窗口二未保存草稿')
  await expect(other.locator('.save-status')).toHaveText('版本冲突 · 未保存')
  await expect(body(other)).toHaveText('窗口二未保存草稿')
  await expect(other.getByRole('button', { name: '添加章节' })).toBeDisabled()
  const downloadPromise = other.waitForEvent('download')
  await other.getByRole('button', { name: '导出未保存草稿' }).click()
  const download = await downloadPromise
  const draft = JSON.parse(readFileSync((await download.path())!, 'utf8'))
  expect(draft.content.content[0].content[0].text).toBe('窗口二未保存草稿')
  other.once('dialog', dialog => dialog.dismiss())
  await other.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(body(other)).toHaveText('窗口二未保存草稿')
  other.once('dialog', dialog => dialog.accept())
  await other.getByRole('button', { name: '重新加载', exact: true }).click()
  await other.getByRole('button', { name: '保留数据库版本', exact: true }).click()
  await expect(body(other)).toHaveText('窗口一正式正文')
  await saved(other)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除当前章节' }).click()
  await expect(page.getByRole('button', { name: '创建第一章' })).toBeVisible()
  await body(other).fill('已删除章节的保留草稿')
  await expect(other.locator('.save-status')).toHaveText('版本冲突 · 未保存')
  other.once('dialog', dialog => dialog.accept())
  await other.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(other.getByRole('button', { name: '创建第一章' })).toBeEnabled()
  await page.getByRole('button', { name: '创建第一章' }).click()
  await other.getByRole('button', { name: '刷新本地数据' }).click()
  await expect(body(other)).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除小说', exact: true }).click()
  await body(other).fill('已删除小说的保留草稿')
  await expect(other.locator('.save-status')).toHaveText('版本冲突 · 未保存')
  other.once('dialog', dialog => dialog.accept())
  await other.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(other.getByRole('heading', { level: 1 })).toHaveText('创作工作台')
  await expect(other.getByRole('button', { name: '创建小说', exact: true }).first()).toBeEnabled()
})

test('network failure keeps the document, retry and keyboard save use the current version', async ({ page }) => {
  await createNovel(page, '保存重试测试')
  await page.getByRole('button', { name: '创建第一章' }).click()
  await expect(body(page)).toBeVisible()
  await page.route('**/api/chapters/*', route => route.request().method() === 'PUT' ? route.abort('failed') : route.continue())
  await body(page).fill('网络失败后仍保留的正文')
  await expect(page.locator('.save-status')).toHaveText('保存失败')
  await expect(body(page)).toHaveText('网络失败后仍保留的正文')
  await page.unroute('**/api/chapters/*')
  await page.getByRole('button', { name: '重试保存' }).click()
  await saved(page)
  await body(page).fill('快捷键保存的正文')
  await body(page).press('Control+Alt+Shift+s')
  await saved(page)
  await page.getByRole('button', { name: '刷新本地数据' }).click()
  await expect(body(page)).toHaveText('快捷键保存的正文')
  await page.getByRole('textbox', { name: '章节标题' }).fill('')
  await expect(page.locator('.save-status')).toHaveText('保存失败')
  await expect(page.getByRole('button', { name: '刷新本地数据' })).toBeDisabled()
  await page.getByRole('textbox', { name: '章节标题' }).fill('修复标题')
  await saved(page)
})

test('native novel dialog traps focus, handles Escape and restores focus', async ({ page }) => {
  await page.goto('/')
  const create = page.getByRole('button', { name: '创建小说', exact: true }).first()
  await create.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('小说名称')).toBeFocused()
  await dialog.getByLabel('小说名称').fill('对话框测试')
  await dialog.getByRole('button', { name: '保存', exact: true }).focus()
  await create.evaluate(element => element.focus())
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(create).toBeFocused()
})

test('chapter mutations remain applied when a subsequent read fails', async ({ page }) => {
  await createNovel(page, '章节请求失败恢复测试')
  await page.route('**/api/novels/*', route => route.request().method() === 'GET' ? route.abort('failed') : route.continue())
  await page.getByRole('button', { name: '创建第一章' }).click()
  await expect(body(page)).toBeVisible()
  await page.getByRole('button', { name: '添加章节' }).click()
  await expect(page.locator('.chapter-select')).toHaveCount(2)
  await body(page).fill('即将删除的测试内容')
  await saved(page)
  await page.unroute('**/api/novels/*')
  await page.route('**/api/chapters/*', route => route.request().method() === 'GET' ? route.abort('failed') : route.continue())
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除当前章节' }).click()
  await expect(page.locator('.chapter-select')).toHaveCount(1)
  await expect(body(page)).not.toBeVisible()
  await expect(page.locator('.workspace-error')).toBeVisible()
  await page.unroute('**/api/chapters/*')
  await page.getByRole('button', { name: '刷新本地数据' }).click()
  await expect(body(page)).toBeVisible()
  await expect(body(page)).not.toContainText('即将删除的测试内容')
})
