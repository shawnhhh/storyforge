const panel = (page: Page) => page.getByRole('region', { name: '创作规划', exact: true })
const saved = (page: Page) => expect(page.locator('.planning-status')).toHaveText('已保存到数据库')
async function seed(page: Page, title: string) {
  const health = await page.request.get('/api/health')
  const headers = { 'X-StoryForge-Generation': health.headers()['x-storyforge-generation'] }
  const response = await page.request.post('/api/novels', { headers, data: { title, description: '隔离数据库，全部为虚构测试资料' } })
  expect(response.ok()).toBeTruthy()
  const novel = await response.json(), root = `/api/novels/${novel.id}`
  const chapterResponse = await page.request.post(root + '/chapters', { headers, data: { title: '初见章节', version: novel.version } })
  expect(chapterResponse.ok()).toBeTruthy()
  const { chapter } = await chapterResponse.json()
  const create = async (path: string, data: unknown) => {
    const result = await page.request.post(root + path, { headers, data }); expect(result.ok()).toBeTruthy(); return result.json()
  }
  const place = await create('/world', { ...newWorld(), name: '北境' })
  const group = await create('/world', { ...newWorld('organization'), name: '观星会' })
  const history = await create('/world', { ...newWorld('history'), name: '旧日之战', timeText: '旧历三年', sortOrder: -10, description: '原有资料库重要事件' })
  const hero = await create('/characters', { ...newCharacter(), name: '寻星', worldIds: [history.id] })
  const references = await page.request.put(root + '/knowledge-links', { headers, data: { version: 0, links: [
    { id: 'history-place', source: { kind: 'world', id: history.id }, target: { kind: 'world', id: place.id }, label: '发生地点', note: '' },
    { id: 'history-chapter', source: { kind: 'chapter', id: chapter.id }, target: { kind: 'world', id: history.id }, label: '记载', note: '' },
  ] } }); expect(references.ok()).toBeTruthy()
  const value = emptyPlanning()
  value.outlines.push({ id: 'overall', title: '寻星总纲', kind: 'overall', parentId: null, content: '', chapterIds: [chapter.id] })
  for (const [id, title, timeOrder] of [['late', '归来', 20], ['early', '启程', 1], ['undated', '未定事件', null]] as const) value.cards.push({
    id, title, content: `${title}事件描述`, summary: '', status: 'planned', plotlineId: null, storyTime: timeOrder === null ? '' : `新纪元 ${timeOrder} 年`, timeOrder, chapterIds: [chapter.id], characterIds: [hero.id], worldIds: [place.id, group.id],
  })
  const planning = await page.request.put(root + '/planning', { headers, data: { ...value, version: 0 } }); expect(planning.ok()).toBeTruthy()
  return { novel, chapter, hero, place, group, history, root, headers }
}
async function open(page: Page, title: string) {
  await page.goto('/')
  // The existing mobile dashboard intentionally hides the sidebar novel list.
  await page.locator('.dashboard-work').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).getByRole('button', { name: '打开作品', exact: true }).click()
  await page.getByRole('button', { name: '创作规划', exact: true }).click()
  await expect(panel(page)).toBeVisible()
}
test('timeline unifies original history with editable card events, filters references and persists edits without copying history', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  const f = await seed(page, '时间线完整流程')
  const before = await (await page.request.get(`/api/chapters/${f.chapter.id}`)).json()
  await open(page, f.novel.title)
  await panel(page).getByRole('button', { name: '故事时间线', exact: true }).click()
  const events = page.locator('.timeline-events>li')
  await expect(events).toHaveCount(4)
  await expect(events.nth(0)).toContainText('旧日之战')
  await expect(events.nth(1)).toContainText('启程')
  await expect(events.nth(2)).toContainText('归来')
  await expect(events.nth(3)).toContainText('未定事件')
  await expect(events.nth(0)).toContainText('寻星'); await expect(events.nth(0)).toContainText('北境')
  await page.screenshot({ path: testInfo.outputPath('timeline-desktop.png') })
  await panel(page).getByLabel('筛选参与人物').selectOption(f.hero.id)
  await panel(page).getByLabel('筛选事件地点').selectOption(f.place.id)
  await panel(page).getByLabel('筛选事件章节').selectOption(f.chapter.id)
  await expect(events).toHaveCount(4)
  await panel(page).getByLabel('筛选事件状态').selectOption('planned')
  await expect(events).toHaveCount(3)
  await panel(page).getByLabel('搜索事件').fill('归来事件描述')
  await expect(events).toHaveCount(1)
  await events.first().getByRole('button', { name: '编辑剧情事件' }).click()
  await expect(panel(page).getByLabel('规划标题', { exact: true })).toHaveValue('归来')
  await panel(page).getByLabel('故事时间序号').fill('-20')
  await panel(page).getByLabel('规划状态').selectOption('done')
  await saved(page)
  await panel(page).getByRole('button', { name: '故事时间线', exact: true }).click()
  await expect(events.first()).toContainText('归来'); await expect(events.first()).toContainText('已完成')
  await page.reload()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: f.novel.title }).click()
  await page.getByRole('button', { name: '创作规划', exact: true }).click()
  await panel(page).getByRole('button', { name: '故事时间线', exact: true }).click()
  await expect(events.first()).toContainText('归来')
  await events.filter({ hasText: '旧日之战' }).getByRole('button', { name: '打开资料库事件' }).click()
  await expect(page.getByLabel('设定名称', { exact: true })).toHaveValue('旧日之战')
  expect((await (await page.request.get(f.root + '/planning')).json()).cards).toHaveLength(3)
  expect((await (await page.request.get(f.root + '/story-bible')).json()).world).toHaveLength(3)
  expect(await (await page.request.get(`/api/chapters/${f.chapter.id}`)).json()).toEqual(before)
  expect(errors).toEqual([])
})

test('outlines link people, locations and other material independently and offer safe reference navigation', async ({ page }) => {
  const f = await seed(page, '大纲资料关联')
  await open(page, f.novel.title)
  await panel(page).getByRole('button', { name: /寻星总纲/ }).first().click()
  await panel(page).getByRole('group', { name: '关联人物', exact: true }).getByLabel('寻星', { exact: true }).check()
  await panel(page).getByRole('group', { name: '关联地点', exact: true }).getByLabel('北境', { exact: true }).check()
  await panel(page).getByRole('group', { name: '其他关联资料', exact: true }).getByLabel('观星会', { exact: true }).check()
  await saved(page)
  await panel(page).getByRole('group', { name: '关联地点', exact: true }).getByLabel('北境', { exact: true }).uncheck()
  await saved(page)
  const snapshot = await (await page.request.get(f.root + '/planning')).json()
  expect(snapshot.outlines[0].characterIds).toEqual([f.hero.id])
  expect(snapshot.outlines[0].worldIds).toEqual([f.group.id])
  expect(snapshot.outlines[0].chapterIds).toEqual([f.chapter.id])
  await panel(page).getByRole('button', { name: '查阅资料 寻星', exact: true }).click()
  await expect(page.getByLabel('姓名', { exact: true })).toHaveValue('寻星')
})

test('event reference drafts survive offline reload and target deletion causes conflict without overwriting newer data', async ({ page }) => {
  const f = await seed(page, '事件草稿与删除冲突')
  await open(page, f.novel.title)
  await panel(page).getByRole('button', { name: '故事时间线', exact: true }).click()
  await panel(page).getByRole('button', { name: '新建事件', exact: true }).click()
  await saved(page)
  await page.route('**/planning', route => route.request().method() === 'PUT' ? route.abort('failed') : route.continue())
  await panel(page).getByLabel('规划标题', { exact: true }).fill('未保存事件')
  await panel(page).getByRole('group', { name: '参与人物', exact: true }).getByLabel('寻星', { exact: true }).check()
  await panel(page).getByRole('group', { name: '关联地点', exact: true }).getByLabel('北境', { exact: true }).check()
  await expect(page.locator('.planning-status')).toHaveText('保存失败 · 草稿已保留')
  page.once('dialog', dialog => dialog.accept()); await page.reload()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: f.novel.title }).click()
  await page.getByRole('button', { name: '创作规划', exact: true }).click()
  await expect(page.getByRole('button', { name: '恢复此草稿', exact: true })).toBeVisible()
  await expect(panel(page).getByRole('button', { name: /^剧情卡片（/ })).toBeDisabled()
  expect((await (await page.request.get(f.root + '/planning')).json()).cards.some((row: { title: string }) => row.title === '未保存事件')).toBe(false)
  await page.getByRole('button', { name: '恢复此草稿', exact: true }).click()
  await panel(page).getByRole('button', { name: /^剧情卡片（/ }).click()
  await panel(page).getByRole('button', { name: /未保存事件/ }).first().click()
  await expect(panel(page).getByRole('group', { name: '参与人物', exact: true }).getByLabel('寻星', { exact: true })).toBeChecked()
  // Wait for the resumed draft's aborted save before removing the route; otherwise
  // the pending request can correctly reach 409 before the retry button is clicked.
  await expect(page.locator('.planning-status')).toHaveText('保存失败 · 草稿已保留')
  const deletion = await page.request.delete(`${f.root}/characters/${f.hero.id}`, { headers: f.headers, data: { version: f.hero.version } }); expect(deletion.ok()).toBeTruthy()
  await page.unroute('**/planning')
  await panel(page).getByRole('button', { name: '重试保存规划', exact: true }).click()
  await expect(page.locator('.planning-status')).toHaveText('版本冲突 · 草稿已保留')
  const download = page.waitForEvent('download')
  await panel(page).getByRole('button', { name: '导出规划草稿', exact: true }).click()
  const file = await download, draft = JSON.parse(readFileSync((await file.path())!, 'utf8'))
  const recoveredEvent = draft.cards.find((row: { title: string }) => row.title === '未保存事件')
  expect(recoveredEvent.characterIds).toEqual([f.hero.id])
  expect(recoveredEvent.worldIds).toEqual([f.place.id])
  expect(draft.cards.find((row: { id: string }) => row.id === 'early').chapterIds).toEqual([f.chapter.id])
  const persisted = await (await page.request.get(f.root + '/planning')).json()
  expect(persisted.cards.some((row: { title: string }) => row.title === '未保存事件')).toBe(false)
  expect(persisted.cards[0].characterIds).toEqual([])
  page.once('dialog', dialog => dialog.accept())
  await panel(page).getByRole('button', { name: '重新加载规划', exact: true }).click()
  await saved(page)
  await panel(page).getByRole('button', { name: '故事时间线', exact: true }).click()
  await expect(page.locator('.timeline-events>li')).toHaveCount(5)
  await expect(page.locator('.timeline-events')).not.toContainText('寻星')
  await expect(page.locator('.timeline-events')).not.toContainText('未保存事件')
  await expect(page.locator('.timeline-events')).toContainText('启程')
  await expect(page.locator('.timeline-events')).toContainText('北境')
})

