import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { newCharacter, newWorld } from '../../src/features/story-bible/model.js'

const module = (page: Page, name: string) => page.getByRole('navigation', { name: '小说工作台模块' }).getByRole('button', { name, exact: true }).click()
const saved = (page: Page) => expect(page.locator('.profile-save-status')).toHaveText('已保存到数据库')
const list = (page: Page) => page.getByRole('navigation', { name: '资料列表', exact: true })
const links = (page: Page) => page.getByRole('region', { name: '资料关联与引用', exact: true })
async function createNovel(page: Page, title: string) {
  await page.goto('/')
  await page.getByRole('button', { name: '创建小说', exact: true }).first().click()
  await page.getByRole('dialog').getByLabel('小说名称').fill(title)
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
}
async function add(page: Page, type: string, name: string) {
  await page.getByLabel('新增资料类型').selectOption(type)
  await page.getByRole('button', { name: '新增资料', exact: true }).first().click()
  await page.getByLabel(type === 'characters' ? '姓名' : '设定名称', { exact: true }).fill(name)
  await saved(page)
}
async function seed(page: Page, title: string) {
  await page.goto('/')
  const result = await page.evaluate(async ({ title, character, world }) => {
    const initial = await fetch('/api/novels'), generation = initial.headers.get('X-StoryForge-Generation')!
    async function post(path: string, data: unknown) {
      const response = await fetch(`/api${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-StoryForge-Generation': generation }, body: JSON.stringify(data) })
      if (!response.ok) throw new Error(await response.text())
      return response.json()
    }
    const novel = await post('/novels', { title, description: '' })
    const root = `/novels/${novel.id}`
    const a = await post(root + '/world', { ...world, name: '测试地点', description: '隔离数据库资料' })
    const b = await post(root + '/world', { ...world, name: '测试势力', category: 'organization' })
    const hero = await post(root + '/characters', { ...character, name: '测试人物' })
    return { novel, a, b, hero }
  }, { title, character: newCharacter(), world: newWorld() })
  await page.reload()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: title }).click()
  await module(page, '创作资料库')
  await list(page).getByRole('button').filter({ hasText: '测试势力' }).click()
  await expect(links(page).getByLabel('引用资料')).toBeEnabled()
  return result
}

