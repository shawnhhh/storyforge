test('Mock write failures retain inputs; stale windows cannot overwrite associations and refresh permits a reviewed retry', async ({ page }) => {
  const fixture = await seed(page, '资料关联失败与冲突验收'), region = links(page)
  await region.getByLabel('引用资料').selectOption({ label: '测试地点 · 地点' })
  await region.getByLabel('引用用途').fill('驻地')
  await region.getByLabel('引用备注').fill('网络失败仍保留的备注')
  await page.route('**/knowledge-links', route => route.request().method() === 'PUT' ? route.abort('failed') : route.continue())
  await region.getByRole('button', { name: '添加关联', exact: true }).click()
  await expect(region.getByRole('alert')).toBeVisible()
  await expect(region.getByLabel('引用备注')).toHaveValue('网络失败仍保留的备注')
  await page.unroute('**/knowledge-links')
  // A real concurrent client updates the same workspace, rather than mocking 409.
  await page.evaluate(async ({ novel, a, b }) => {
    const url = `/api/novels/${novel.id}/knowledge-links`, current = await fetch(url), generation = current.headers.get('X-StoryForge-Generation')!
    const response = await fetch(url, { method: 'PUT', headers: { 'Content-Type': 'application/json', 'X-StoryForge-Generation': generation }, body: JSON.stringify({ version: 0, links: [{ id: 'concurrent-link', source: { kind: 'world', id: a.id }, target: { kind: 'world', id: b.id }, label: '归属', note: '另一窗口的资料' }] }) })
    if (!response.ok) throw new Error(await response.text())
  }, fixture)
  await region.getByRole('button', { name: '添加关联', exact: true }).click()
  await expect(region.getByRole('alert')).toContainText('其他窗口')
  await expect(region.getByLabel('引用备注')).toHaveValue('网络失败仍保留的备注')
  await expect(region.getByLabel('引用资料')).toBeDisabled()
  await region.getByRole('button', { name: '刷新关联', exact: true }).click()
  await expect(region.getByLabel('引用资料')).toBeEnabled()
  await expect(region.getByRole('button', { name: '测试地点', exact: true })).toBeVisible()
  await region.getByRole('button', { name: '添加关联', exact: true }).click()
  await expect(region.getByText('网络失败仍保留的备注', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '刷新资料', exact: true }).click()
  await expect(links(page).getByText('网络失败仍保留的备注', { exact: true })).toBeVisible()
})

test('library deletion cleans chapter references and narrow layouts keep controls within the viewport', async ({ page }) => {
  await seed(page, '资料库删除与窄屏验收')
  await module(page, '章节写作')
  await page.getByRole('button', { name: '创建第一章' }).click()
  await expect(page.getByRole('textbox', { name: '小说正文' })).toBeEditable()
  await page.getByRole('button', { name: '查阅与引用创作资料' }).click()
  const references = page.getByRole('region', { name: '章节资料引用' })
  await references.getByLabel('引用资料').selectOption({ label: '测试地点 · 地点' })
  await references.getByRole('button', { name: '添加引用', exact: true }).click()
  await expect(references.getByRole('button', { name: '测试地点', exact: true })).toBeVisible()
  await module(page, '创作资料库')
  await list(page).getByRole('button').filter({ hasText: '测试势力' }).click()
  for (const width of [1440, 1024, 700, 390]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await links(page).getByLabel('引用资料').selectOption({ label: '测试地点 · 地点' })
  await links(page).getByRole('button', { name: '添加关联', exact: true }).click()
  await expect(links(page).getByRole('button', { name: '测试地点', exact: true })).toBeVisible()
  await list(page).getByRole('button').filter({ hasText: '测试地点' }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '删除资料', exact: true }).click()
  await expect(page.getByLabel('设定名称', { exact: true })).toHaveValue('测试地点')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除资料', exact: true }).click()
  await expect(list(page).getByRole('button')).toHaveCount(2)
  await list(page).getByRole('button').filter({ hasText: '测试势力' }).click()
  await expect(links(page).getByRole('button', { name: '测试地点', exact: true })).toHaveCount(0)
  await page.getByLabel('搜索资料', { exact: true }).fill('不存在的资料')
  await expect(page.getByText('没有匹配的资料', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await expect(list(page).getByRole('button')).toHaveCount(2)
  await module(page, '章节写作')
  await page.getByRole('button', { name: '查阅与引用创作资料' }).click()
  await expect(references.getByRole('button', { name: '测试地点', exact: true })).toHaveCount(0)
  await expect(references.getByLabel('引用资料')).not.toContainText('测试地点')
  await expect(page.getByRole('textbox', { name: '小说正文' })).toBeEmpty()
})
