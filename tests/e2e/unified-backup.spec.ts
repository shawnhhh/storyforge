import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
test('unified local download, integrity preview, selective restore and duplicate prevention',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'创建小说',exact:true}).first().click()
 await page.getByRole('dialog').getByLabel('小说名称').fill('统一备份原小说')
 await page.getByRole('dialog').getByRole('button',{name:'保存',exact:true}).click()
 await page.getByRole('button',{name:'备份与恢复',exact:true}).click()
 const panel=page.getByRole('region',{name:'三模块统一备份'})
 const health=await page.request.get('/api/health'),headers={'X-StoryForge-Generation':health.headers()['x-storyforge-generation']}
 const source=await page.request.post('/api/studio/projects',{headers,data:{kind:'music',title:'统一音乐'}});expect(source.status()).toBe(201)
 const music=await source.json()
 const download=page.waitForEvent('download');await panel.getByRole('button',{name:'导出完整统一备份',exact:true}).click()
 const file=await download;expect(file.suggestedFilename()).toBe('storyforge-unified.json')
 const data=readFileSync((await file.path())!);const archive=JSON.parse(data.toString())
 expect(archive.format).toBe('storyforge-unified');expect(archive.story.novels.length).toBeGreaterThan(0)
 await panel.getByLabel('选择统一备份 JSON').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:data})
 await expect(panel.getByRole('heading',{name:'统一恢复预览',exact:true})).toBeVisible()
 await panel.getByRole('checkbox',{name:'小说',exact:true}).uncheck()
 await panel.getByRole('checkbox',{name:'视频',exact:true}).uncheck()
 await panel.getByRole('checkbox',{name:'浏览器草稿收件箱',exact:true}).uncheck()
 await panel.getByRole('button',{name:'确认恢复为新副本',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('所选模块已恢复为新副本')
 const projects=await(await page.request.get('/api/studio/projects?kind=music')).json();expect(projects.filter((p:{title:string})=>p.title.includes('统一音乐')).length).toBe(2)
 expect(await(await page.request.get(`/api/studio/projects/${music.id}`)).json()).toEqual(music)
 const preview=await page.request.post('/api/unified-backups/preview',{headers,data:{archive}});expect(preview.status()).toBe(200)
 expect((await page.request.post('/api/unified-backups/restore',{headers,data:{archive,token:(await preview.json()).token,modules:['music'],confirmation:'恢复为新副本'}})).status()).toBe(409)
 archive.sha256='bad';expect((await page.request.post('/api/unified-backups/preview',{headers,data:{archive}})).status()).toBe(400)
})
