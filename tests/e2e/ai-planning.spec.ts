const dialog = (page: Page) => page.getByRole('dialog', { name: 'AI 世界观与大纲', exact: true })
async function seed(page: Page) {
  const health = await page.request.get('/api/health'), headers = { 'X-StoryForge-Generation': health.headers()['x-storyforge-generation'] }
  const novel = await (await page.request.post('/api/novels', { headers, data: { title: `AI规划-${crypto.randomUUID()}`, description: '不可自动发送的原稿简介' } })).json()
  const created = await (await page.request.post(`/api/novels/${novel.id}/chapters`, { headers, data: { title: '原有章节', version: novel.version } })).json()
  const plan = emptyPlanning()
  plan.outlines.push({ id: 'overall', title: '原有总纲', content: '不可覆盖的规划', kind: 'overall', parentId: null, chapterIds: [] }, { id: 'volume', title: '原有分卷', content: '不可覆盖的分卷', kind: 'volume', parentId: 'overall', chapterIds: [] })
  const response = await page.request.put(`/api/novels/${novel.id}/planning`, { headers, data: { ...plan, version: 0 } }); expect(response.ok()).toBeTruthy()
  return { novel, chapter: created.chapter, plan, headers }
}
async function open(page: Page, title: string) {
  await page.goto('/')
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: title }).click()
  await page.getByRole('button', { name: '创作规划', exact: true }).click()
  await page.getByRole('button', { name: 'AI 世界观与大纲', exact: true }).click()
  await expect(dialog(page).getByRole('button', { name: '核对发送内容' })).toBeVisible()
}
async function generate(page: Page, kind = 'world', instructions = '生成一项原创悬疑设定') {
  const modal = dialog(page)
  await modal.getByLabel('生成类型').selectOption(kind)
  await modal.getByLabel('创作要求').fill(instructions)
  await modal.getByRole('button', { name: '核对发送内容', exact: true }).click()
  await expect(modal.getByLabel('发送内容预览')).toBeVisible()
  await modal.getByRole('button', { name: '确认发送并生成', exact: true }).click()
  await expect(modal.getByLabel('预览标题')).toHaveValue('AI 虚构预览')
}
