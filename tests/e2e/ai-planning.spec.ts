import { expect, test, type Page } from '@playwright/test'
import { defaultPreferences, preferencesKey } from '../../src/features/preferences/model.js'
import { emptyPlanning } from '../../shared/contracts/planning.js'
const dialog = (page: Page) => page.getByRole('dialog', { name: 'AI 世界观与大纲', exact: true })
async function seed(page: Page) {
  const health = await page.request.get('/api/health'), headers = { 'X-StoryForge-Generation': health.headers()['x-storyforge-generation'] }
  const novel = await (await page.request.post('/api/novels', { headers, data: { title: `AI规划-${crypto.randomUUID()}`, description: '不可自动发送的原稿简介' } })).json()
  const created = await (await page.request.post(`/api/novels/${novel.id}/chapters`, { headers, data: { title: '原有章节', version: novel.version } })).json()
  const plan = emptyPlanning()
  plan.outlines.push({ id: 'overall', title: '原有总纲', content: '不可覆盖的规划', kind: 'overall', parentId: null, chapterIds: [] }, { id: 'volume', title: '原有分卷', content: '不可覆盖的分卷', kind: 'volume', parentId: 'overall', chapterIds: [] })
  const response = await page.request.put(`/api/novels/${novel.id}/planning`, { headers, data: { ...plan, version: 0 } }); expect(response.ok()).toBeTruthy()
  return { novel, chapter: created.chapter, plan, headers }
}
async function open(page: Page, title: string) {
  await page.goto('/')
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: title }).click()
  await page.getByRole('button', { name: '创作规划', exact: true }).click()
  await page.getByRole('button', { name: 'AI 世界观与大纲', exact: true }).click()
  await expect(dialog(page).getByRole('button', { name: '核对发送内容' })).toBeVisible()
}
async function generate(page: Page, kind = 'world', instructions = '生成一项原创悬疑设定') {
  const modal = dialog(page)
  await modal.getByLabel('生成类型').selectOption(kind)
  await modal.getByLabel('创作要求').fill(instructions)
  await modal.getByRole('button', { name: '核对发送内容', exact: true }).click()
  await expect(modal.getByLabel('发送内容预览')).toBeVisible()
  await modal.getByRole('button', { name: '确认发送并生成', exact: true }).click()
  await expect(modal.getByLabel('预览标题')).toHaveValue('AI 虚构预览')
}
const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const list: string[] = []; errors.set(page, list); page.on('pageerror', error => list.push(error.message)) })
test.afterEach(({ page }) => { expect(errors.get(page)).toEqual([]) })
for (const kind of ['world', 'character', 'volume', 'chapter']) test(`${kind}: real preview/edit/confirm/save appends without touching original chapters or outlines`, async ({ page }) => {
  const f = await seed(page)
  await open(page, f.novel.title)
  const before = await (await page.request.get(`/api/chapters/${f.chapter.id}`)).json()
  const modal = dialog(page)
  await modal.getByLabel('生成类型').selectOption(kind)
  if (kind === 'volume' || kind === 'chapter') await modal.getByLabel('归属大纲').selectOption(kind === 'volume' ? 'overall' : 'volume')
  if (kind === 'chapter') await modal.getByRole('group', { name: '关联已有章节（可选）' }).getByLabel('原有章节').check()
  await modal.getByLabel('创作要求').fill('生成一项原创悬疑设定')
  await expect(modal.getByRole('button', { name: '确认新增保存' })).toHaveCount(0)
  await modal.getByRole('button', { name: '核对发送内容', exact: true }).click()
  await expect(modal.getByLabel('发送内容预览')).not.toContainText('不可自动发送的原稿简介')
  await modal.getByRole('button', { name: '确认发送并生成', exact: true }).click()
  await expect(modal.getByLabel('预览标题')).toHaveValue('AI 虚构预览')
  await expect(modal.locator('script')).toHaveCount(0)
  const notSaved = await (await page.request.get(`/api/novels/${f.novel.id}/planning`)).json()
  expect(notSaved.outlines).toEqual(f.plan.outlines)
  await modal.getByLabel('预览标题').fill('用户确认的设定')
  await modal.getByLabel('预览内容').fill('人工修订后的完整内容🌕')
  await modal.getByRole('button', { name: '确认新增保存', exact: true }).click()
  await expect(modal.getByRole('button', { name: '已保存', exact: true })).toBeDisabled()
  const plan = await (await page.request.get(`/api/novels/${f.novel.id}/planning`)).json()
  expect(plan.outlines.slice(0, 2)).toEqual(f.plan.outlines)
  if (kind === 'volume' || kind === 'chapter') {
    expect(plan.outlines[2]).toMatchObject({ title: '用户确认的设定', content: '人工修订后的完整内容🌕', parentId: kind === 'volume' ? 'overall' : 'volume', chapterIds: kind === 'chapter' ? [f.chapter.id] : [] })
  } else {
    const bible = await (await page.request.get(`/api/novels/${f.novel.id}/story-bible`)).json()
    const saved = kind === 'world' ? bible.world[0] : bible.characters[0]
    expect(saved.name).toBe('用户确认的设定')
    expect(kind === 'world' ? saved.description : saved.fields.notes).toBe('人工修订后的完整内容🌕')
  }
  expect(await (await page.request.get(`/api/chapters/${f.chapter.id}`)).json()).toEqual(before)
  await modal.getByRole('button', { name: '关闭AI 世界观与大纲' }).click()
  await expect(modal).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'AI 世界观与大纲', exact: true })).toBeFocused()
})
test('cancel and provider error keep original data, stale saves preserve exportable preview', async ({ page }) => {
  const f = await seed(page)
  await open(page, f.novel.title)
  const modal = dialog(page)
  await modal.getByLabel('创作要求').fill('mock-slow')
  await modal.getByRole('button', { name: '核对发送内容', exact: true }).click()
  await modal.getByRole('button', { name: '确认发送并生成', exact: true }).click()
  await modal.getByRole('button', { name: '取消请求', exact: true }).click()
  await expect(modal.getByRole('status')).toContainText('请求已取消')
  await modal.getByLabel('创作要求').fill('mock-error')
  await modal.getByRole('button', { name: '核对发送内容', exact: true }).click()
  await modal.getByRole('button', { name: '确认发送并生成', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('模拟模型服务暂时不可用')
  await generate(page)
  const plan = await (await page.request.get(`/api/novels/${f.novel.id}/planning`)).json()
  const response = await page.request.put(`/api/novels/${f.novel.id}/planning`, { headers: f.headers, data: { ...plan, outlines: plan.outlines.map((row: { id: string }) => row.id === 'overall' ? { ...row, title: '另一窗口更新' } : row) } }); expect(response.ok()).toBeTruthy()
  await modal.getByRole('button', { name: '确认新增保存', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('已变化')
  await expect(modal.getByLabel('预览内容')).toHaveValue(/浮空岛/)
  const download = page.waitForEvent('download')
  await modal.getByRole('button', { name: '导出预览', exact: true }).click()
  expect((await download).suggestedFilename()).toContain('AI预览')
  expect((await (await page.request.get(`/api/novels/${f.novel.id}/planning`)).json()).outlines[0].title).toBe('另一窗口更新')
})
test('light, dark and system themes update dialog and narrow view without overflow', async ({ page }) => {
  const f = await seed(page)
  await page.addInitScript(({ key, preferences }) => localStorage.setItem(key, JSON.stringify(preferences)), { key: preferencesKey, preferences: defaultPreferences })
  await page.emulateMedia({ colorScheme: 'light' }); await open(page, f.novel.title)
  const modal = dialog(page)
  await expect(modal).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(modal).toHaveCSS('background-color', 'rgb(31, 31, 34)')
  await expect(modal.getByLabel('创作要求')).toHaveCSS('color', 'rgb(242, 242, 247)')
  await page.evaluate(({ key, preferences }) => { localStorage.setItem(key, JSON.stringify(preferences)); window.dispatchEvent(new StorageEvent('storage', { key })) }, { key: preferencesKey, preferences: { ...defaultPreferences, theme: 'light' } })
  await expect(modal).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(modal).toBeVisible()
  expect(await modal.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await modal.getByRole('button', { name: '关闭AI 世界观与大纲' }).click()
})
