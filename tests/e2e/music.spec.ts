import { test, expect } from '@playwright/test'
for (const width of [1440, 390]) test(`music project lyrics history mock audio import and export ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 })
  let release!: () => void
  const initialList = new Promise<void>(resolve => { release = resolve })
  await page.route(/\/api\/studio\/projects\?kind=music$/, async route => { await initialList; await route.continue() })
  await page.goto('/#music')
  await expect(page.getByRole('heading', { name: '音乐工作台' })).toBeVisible()
  await page.getByLabel('歌曲名称', { exact: true }).fill(`临时歌曲-${width}`)
  await expect(page.getByRole('button', { name: '创建歌曲', exact: true })).toBeDisabled()
  release()
  await expect(page.getByRole('button', { name: '创建歌曲', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '创建歌曲', exact: true }).click()
  await expect(page.getByLabel('项目标题', { exact: true })).toHaveValue(`临时歌曲-${width}`)
  await page.getByLabel('歌词', { exact: true }).fill('[主歌]\n虚构的月亮照亮归途\n[副歌]\n向星海航行')
  await page.getByLabel('曲风', { exact: true }).fill('爵士')
  await page.getByLabel('情绪', { exact: true }).fill('宁静')
  await page.getByLabel('速度（BPM）').fill('84')
  await page.getByLabel('歌曲结构（用逗号分隔）').fill('主歌,副歌,桥段,尾奏')
  await expect(page.getByRole('button', { name: '生成 Mock 音乐' })).toBeDisabled()
  await page.getByRole('button', { name: '保存歌词与配置' }).click()
  await expect(page.getByRole('status')).toContainText('歌词与配置已保存')
  await page.reload()
  await page.getByRole('button', { name: `临时歌曲-${width}`, exact: true }).click()
  await expect(page.getByLabel('歌词', { exact: true })).toHaveValue(/虚构的月亮/)
  await expect(page.getByLabel('速度（BPM）')).toHaveValue('84')
  await page.getByLabel('歌词', { exact: true }).fill('新的虚构歌词')
  await page.getByRole('button', { name: '保存歌词与配置' }).click()
  await expect(page.getByRole('status')).toContainText('歌词与配置已保存')
  await page.locator('summary').filter({ hasText: '歌词历史版本' }).click()
  const versions = page.getByRole('button', { name: /^载入版本/ })
  await expect(versions.first()).toBeVisible()
  await expect(versions).not.toHaveCount(0)
  const oldLyrics = await page.getByLabel('歌词', { exact: true }).inputValue()
  await versions.nth(1).click()
  await expect(page.getByText('有未保存编辑', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '放弃本次编辑' }).click()
  await expect(page.getByLabel('歌词', { exact: true })).toHaveValue(oldLyrics)
  await page.getByRole('button', { name: '生成 Mock 音乐' }).click()
  await expect(page.getByRole('list', { name: '生成任务' })).toContainText('completed', { timeout: 15000 })
  const audio = page.locator('audio').first()
  await expect(audio).toBeVisible()
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).duration)).toBeGreaterThan(0)
  await audio.evaluate(element => (element as HTMLAudioElement).play())
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(0)
  const url = await audio.getAttribute('src')
  const generated = await page.request.get(url!)
  expect(generated.ok()).toBe(true)
  const bytes = await generated.body()
  expect(bytes.subarray(0, 4).toString()).toBe('RIFF')
  await page.getByLabel('导入音频（≤500 KB）').setInputFiles({ name: '隔离试听.wav', mimeType: 'audio/wav', buffer: bytes })
  await expect(page.getByLabel('隔离试听.wav', { exact: true })).toBeVisible()
  const exportedUrl = await page.getByRole('link', { name: '导出完整歌曲项目' }).getAttribute('href')
  const exported = await page.request.get(exportedUrl!)
  expect(exported.ok()).toBe(true)
  const body = await exported.json()
  expect(JSON.stringify(body)).toContain('新的虚构歌词')
  expect(JSON.stringify(body)).toContain('隔离试听.wav')
  expect(JSON.stringify(body)).toContain('爵士')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await test.info().attach(`music-workbench-${width}`, { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
})
test('music stale save preserves lyrics and wrong-project navigation remains blocked', async ({ page }) => {
  await page.goto('/#music')
  await page.getByLabel('歌曲名称', { exact: true }).fill('虚构冲突歌曲')
  const created = page.waitForResponse(response => response.url().endsWith('/api/studio/projects') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '创建歌曲', exact: true }).click()
  const song = await (await created).json()
  await expect(page.getByLabel('项目标题', { exact: true })).toHaveValue('虚构冲突歌曲')
  await page.getByLabel('歌词', { exact: true }).fill('必须保留的未保存歌词')
  const health = await page.request.get('/api/health')
  const headers = { 'X-StoryForge-Generation': health.headers()['x-storyforge-generation'] }
  const concurrent = await page.request.put(`/api/studio/projects/${song.id}`, { headers, data: { ...song, content: '另一窗口已保存的歌词' } })
  expect(concurrent.ok()).toBe(true)
  await page.getByRole('button', { name: '保存歌词与配置' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('歌词', { exact: true })).toHaveValue('必须保留的未保存歌词')
  await page.evaluate(() => { location.hash = '#story' })
  await expect(page).toHaveURL(/#music$/)
  await expect(page.getByLabel('歌词', { exact: true })).toHaveValue('必须保留的未保存歌词')
  await page.getByRole('link', { name: '小说工作台', exact: true }).click()
  await expect(page).toHaveURL(/#music$/)
  await expect(page.getByLabel('歌词', { exact: true })).toHaveValue('必须保留的未保存歌词')
  const persisted = await page.request.get(`/api/studio/projects/${song.id}`)
  expect((await persisted.json()).content).toBe('另一窗口已保存的歌词')
  await page.getByRole('button', { name: '放弃本次编辑' }).click()
})
