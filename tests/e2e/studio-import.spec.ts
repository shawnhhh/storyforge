import { test, expect } from '@playwright/test'
for (const kind of ['music','video'] as const) test(`${kind} import preview confirmation and repeat protection through real API`,async({page})=>{
 await page.goto(`/#${kind}`)
 const health=await page.request.get('/api/health')
 const headers={'X-StoryForge-Generation':health.headers()['x-storyforge-generation']}
 const source=await page.request.post('/api/studio/projects',{headers,data:{kind,title:`导入测试-${kind}`}})
 expect(source.status()).toBe(201)
 const p=await source.json()
 const exported=await page.request.get(`/api/studio/projects/${p.id}/export`)
 const archive=await exported.json()
 await page.getByLabel('导入工程 JSON',{exact:true}).setInputFiles({name:'project.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(archive))})
 await expect(page.getByRole('heading',{name:`导入预览：${p.title}`})).toBeVisible()
 await page.getByRole('button',{name:'确认作为新项目导入'}).click()
 await expect(page.getByText('工程已作为新项目导入',{exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:/导入副本/})).toBeVisible()
 const duplicate=await page.request.post('/api/studio/import/preview',{headers,data:{archive}})
 expect(duplicate.status()).toBe(409)
 const original=await page.request.get(`/api/studio/projects/${p.id}`)
 expect(await original.json()).toEqual(p)
 const corrupt=structuredClone(archive); corrupt.project.content='corrupt'
 expect((await page.request.post('/api/studio/import/preview',{headers,data:{archive:corrupt}})).status()).toBe(400)
})
test('unsaved music blocks hash navigation; unsaved video cancellation preserves script',async({page})=>{
 await page.goto('/#music')
 await page.getByLabel('歌曲名称',{exact:true}).fill('导航草稿')
 await page.getByRole('button',{name:'创建歌曲',exact:true}).click()
 await page.getByRole('textbox',{name:'歌词',exact:true}).fill('未保存歌词')
 await page.evaluate(()=>{location.hash='#video'})
 await expect(page.getByRole('heading',{name:'音乐工作台',exact:true})).toBeVisible()
 await expect(page.getByRole('textbox',{name:'歌词',exact:true})).toHaveValue('未保存歌词')
 await expect(page).toHaveURL(/#music$/)
 await page.getByRole('button',{name:'放弃本次编辑',exact:true}).click()
 await expect(page.getByRole('button',{name:'放弃本次编辑',exact:true})).toHaveCount(0)
 await page.evaluate(()=>{location.hash='#video'})
 await page.getByRole('button',{name:'新建视频项目',exact:true}).click()
 await page.getByRole('textbox',{name:'剧本',exact:true}).fill('未保存剧本')
 const cancelled=page.waitForEvent('dialog').then(async dialog=>{expect(dialog.type()).toBe('confirm');await dialog.dismiss()})
 await page.getByRole('link',{name:'小说',exact:true}).click()
 await cancelled
 await expect(page).toHaveURL(/#video$/)
 await expect(page.getByRole('textbox',{name:'剧本',exact:true})).toHaveValue('未保存剧本')
})
