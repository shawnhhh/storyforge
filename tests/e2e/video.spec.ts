async function create(page: Page, title: string) {
  await page.goto('/#video')
  await expect(page.getByRole('heading', { name: '视频工作台', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新建视频项目', exact: true }).click()
  await page.getByLabel('视频名称', { exact: true }).fill(title)
  await page.getByLabel('剧本', { exact: true }).fill('清晨，小船驶入虚构港湾。')
  await page.getByRole('button', { name: '添加镜头', exact: true }).click()
  await page.getByLabel('镜头描述 1', { exact: true }).fill('俯瞰港湾，晨光照在小船上。')
  await page.getByLabel('时长 1（秒）', { exact: true }).fill('7')
  await page.getByLabel('运镜 1', { exact: true }).fill('缓慢推进')
  await page.getByLabel('画面比例', { exact: true }).selectOption('9:16')
  await page.getByRole('button', { name: '保存视频项目', exact: true }).click()
  await expect(page.locator('[data-video-message]')).toHaveText('已保存到数据库')
}
