test('video refuses invalid shots and retains unsaved edits after a stale-version conflict', async ({ page }) => {
  await create(page, `安全测试 ${Date.now()}`)
  await page.getByLabel('时长 1（秒）', { exact: true }).fill('0')
  await page.getByRole('button', { name: '保存视频项目', exact: true }).click()
  await expect(page.locator('[data-video-message]')).toContainText('镜头时长须为 1–60 秒')
  await page.getByLabel('时长 1（秒）', { exact: true }).fill('7')
  const link = await page.getByRole('link', { name: '导出工程 JSON', exact: true }).getAttribute('href')
  const id = link!.split('/').at(-2)
  const response = await page.request.get(`/api/studio/projects/${id}`)
  const current = await response.json()
  const generation = (await page.request.get('/api/health')).headers()['x-storyforge-generation']
  const updated = await page.request.put(`/api/studio/projects/${id}`, { headers: { 'X-StoryForge-Generation': generation }, data: { ...current, title: '另一个窗口的保存' } })
  expect(updated.status()).toBe(200)
  await page.getByLabel('剧本', { exact: true }).fill('本窗口未保存的宝贵剧本')
  await page.getByRole('button', { name: '保存视频项目', exact: true }).click()
  await expect(page.locator('[data-video-message]')).toContainText(/冲突|版本/)
  await expect(page.getByLabel('剧本', { exact: true })).toHaveValue('本窗口未保存的宝贵剧本')
  expect((await (await page.request.get(`/api/studio/projects/${id}`)).json()).title).toBe('另一个窗口的保存')
  await expect(page.getByRole('button', { name: '生成 Mock 视频', exact: true })).toBeDisabled()
})
