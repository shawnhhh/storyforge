  const exported = JSON.parse(Buffer.concat(chunks).toString())
  expect(JSON.stringify(exported)).toContain('晨光照在小船上')
  expect(JSON.stringify(exported)).toContain('video/webm')
  await page.reload()
  await page.getByRole('navigation', { name: '视频项目列表' }).getByRole('button', { name: title, exact: true }).click()
  await expect(page.getByLabel('剧本', { exact: true })).toHaveValue('清晨，小船驶入虚构港湾。')
  await expect(page.getByLabel('时长 1（秒）', { exact: true })).toHaveValue('7')
  await expect(page.getByLabel('画面比例', { exact: true })).toHaveValue('9:16')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: test.info().outputPath(`video-workspace-${width}.png`), fullPage: true })
