test('failed network drafts restore after refresh, composition defers saves and novel data stays isolated on mobile', async ({ page }) => {
  const { novel } = await seed(page, '草稿恢复与隔离甲'), other = await seed(page, '草稿恢复与隔离乙')
  await open(page, novel.title)
  await panel(page).getByRole('button', { name: '新建大纲', exact: true }).click()
  await saved(page)
  const title = panel(page).getByLabel('规划标题', { exact: true })
  let writes = 0
  await page.route('**/api/novels/*/planning', route => {
    if (route.request().method() === 'PUT') { writes++; return route.abort('failed') }
    return route.continue()
  })
  await title.dispatchEvent('compositionstart')
  await title.fill('中文组合草稿')
  // Stay beyond the debounce interval; no write may interrupt the composition.
  await page.waitForTimeout(850)
  expect(writes).toBe(0)
  await expect(title).toHaveValue('中文组合草稿')
  await title.dispatchEvent('compositionend')
  await expect(page.locator('.planning-status')).toHaveText('保存失败 · 草稿已保留')
  expect(writes).toBe(1)
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: novel.title }).click()
  await page.getByRole('button', { name: '创作规划', exact: true }).click()
  await expect(page.locator('.planning-items')).toContainText('中文组合草稿')
  await expect(page.locator('.planning-status')).toHaveText('保存失败 · 草稿已保留')
  await page.unroute('**/api/novels/*/planning')
  await panel(page).getByRole('button', { name: '重试保存规划', exact: true }).click()
  await saved(page)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: other.novel.title }).click()
  await expect(panel(page)).toBeVisible()
  await expect(page.locator('.planning-items article')).toHaveCount(0)
  await page.getByRole('navigation', { name: '小说列表' }).getByRole('button', { name: novel.title }).click()
  await expect(page.locator('.planning-items')).toContainText('中文组合草稿')
})

test('two browser pages protect conflicting planning drafts and export them without overwriting', async ({ page, context }) => {
  const { novel } = await seed(page, '规划双窗口保护')
  await open(page, novel.title)
  const other = await context.newPage(); await open(other, novel.title)
  await panel(page).getByRole('button', { name: '新建大纲', exact: true }).click()
  await panel(page).getByLabel('规划标题', { exact: true }).fill('正式大纲')
  await saved(page)
  await panel(other).getByRole('button', { name: '新建大纲', exact: true }).click()
  await panel(other).getByLabel('规划标题', { exact: true }).fill('冲突草稿')
  await expect(other.locator('.planning-status')).toHaveText('版本冲突 · 草稿已保留')
  const promise = other.waitForEvent('download')
  await panel(other).getByRole('button', { name: '导出规划草稿', exact: true }).click()
  const download = await promise
  const draft = JSON.parse(readFileSync((await download.path())!, 'utf8'))
  expect(draft.outlines[0].title).toBe('冲突草稿')
  const persisted = await (await page.request.get(`/api/novels/${novel.id}/planning`)).json()
  expect(persisted.outlines[0].title).toBe('正式大纲')
  other.once('dialog', dialog => dialog.accept())
  await panel(other).getByRole('button', { name: '重新加载规划', exact: true }).click()
  await expect(other.locator('.planning-items')).toContainText('正式大纲')
  await saved(other)
})

