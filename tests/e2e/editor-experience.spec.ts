/// <reference lib="dom" />
import { expect, test, type Page } from '@playwright/test'
import { chapterBody, expectChapterReady } from './editor-helpers.js'

const body = chapterBody
const title = (page: Page) => page.getByRole('textbox', { name: '章节标题' })
const saved = (page: Page) => expect(page.locator('.save-status')).toHaveText('已保存到数据库')
async function start(page: Page, name: string, second = false) {
  await page.goto('/')
  await page.getByRole('button', { name: '创建小说', exact: true }).first().click()
  await page.getByRole('dialog').getByLabel('小说名称').fill(`第四阶段虚构测试-${name}`)
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '创建第一章' }).click()
  await expectChapterReady(page, '第 1 章')
  if (second) {
    await page.getByRole('button', { name: '添加章节' }).click()
    await expectChapterReady(page, '第 2 章')
    await page.getByRole('button', { name: '上一章', exact: true }).click()
    await expectChapterReady(page, '第 1 章')
  }
}
const browserErrors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const errors: string[] = []
  browserErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
})
test.afterEach(({ page }) => { expect(browserErrors.get(page)).toEqual([]) })

test('live counts explain mixed prose and remain correct through formatting and undo', async ({ page }) => {
  await start(page, '字数规则')
  await body(page).fill("你好，世界！Hello world, don't stop. 2026 😀")
  await expect(page.getByLabel('字数统计')).toHaveText('9 字')
  await page.getByLabel('字数统计').click()
  await expect(page.locator('.statistics-details')).toContainText('中文 4 字 · 英文 4 词 · 数字 1 组')
  await expect(page.locator('.statistics-details')).toContainText('标点、符号与表情不计入')
  await body(page).press('ControlOrMeta+a')
  await page.getByRole('button', { name: '粗体', exact: true }).click()
  await expect(page.getByLabel('字数统计')).toHaveText('9 字')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.getByLabel('字数统计')).toHaveText('9 字')
  await saved(page)
  // Hold the real chapter read so this race is deterministic on fast and slow CI:
  // the old 9-word editor stays visible but must be locked while refresh is pending.
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/chapters/*', async route => {
    if (route.request().method() === 'GET') await gate
    await route.continue()
  })
  try {
    await page.getByRole('button', { name: '刷新本地数据' }).click()
    await expect(page.locator('.workspace')).toHaveAttribute('aria-busy', 'true')
    await expect(body(page)).toHaveAttribute('contenteditable', 'false')
    await expect(page.getByLabel('字数统计')).toHaveText('9 字')
    await test.info().attach('refresh-loading-state', { body: await page.locator('.workspace').ariaSnapshot(), contentType: 'text/plain' })
  } finally { release() }
  await expectChapterReady(page, '第 1 章', "你好，世界！Hello world, don't stop. 2026 😀")
  await page.unroute('**/api/chapters/*')
  await expect(page.getByLabel('字数统计')).toHaveText('9 字')
  await body(page).fill('，。！？😀 \n\t')
  await expect(page.getByLabel('字数统计')).toHaveText('0 字')
  await saved(page)
})

test('navigation waits for a pending save, searches chapters and preserves drafts on load failure', async ({ page }) => {
  await start(page, '切章保存', true)
  await page.clock.install()
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/chapters/*', async route => {
    if (route.request().method() === 'PUT') await gate
    await route.continue()
  })
  await body(page).fill('必须先保存的第一章正文')
  await expect(page.locator('.save-status')).toHaveText('未保存 · 等待自动保存')
  await page.getByRole('button', { name: '下一章', exact: true }).click()
  await expect(page.locator('.save-status')).toHaveText('保存中…')
  await expect(title(page)).toHaveValue('第 1 章')
  await expect(page.getByRole('button', { name: '下一章', exact: true })).toBeDisabled()
  release()
  await expect(title(page)).toHaveValue('第 2 章')
  await page.unroute('**/api/chapters/*')
  await page.getByRole('button', { name: '上一章', exact: true }).click()
  await expect(body(page)).toHaveText('必须先保存的第一章正文')
  await page.getByLabel('搜索章节').fill('2')
  await expect(page.locator('.chapter-select:visible')).toHaveCount(1)
  await expect(page.locator('.chapter-select:visible')).toContainText('第 2 章')
  await page.getByLabel('搜索章节').fill('不存在的标题')
  await expect(page.getByText('没有匹配的章节', { exact: true })).toBeVisible()
  await page.getByLabel('搜索章节').fill('')
  await page.route('**/api/chapters/*', route => route.request().method() === 'GET' ? route.abort('failed') : route.continue())
  await page.getByLabel('跳转章节').selectOption({ index: 1 })
  await expect(page.locator('.workspace-error')).toBeVisible()
  await expect(body(page)).toHaveText('必须先保存的第一章正文')
  await page.unroute('**/api/chapters/*')
  await page.getByRole('button', { name: '下一章', exact: true }).click()
  await expect(title(page)).toHaveValue('第 2 章')
  await expect(page.getByRole('button', { name: '下一章', exact: true })).toBeDisabled()
})

test('failed navigation retains the current chapter until explicit retry succeeds', async ({ page }) => {
  await start(page, '切章失败', true)
  await page.clock.install()
  await page.route('**/api/chapters/*', route => route.request().method() === 'PUT' ? route.abort('failed') : route.continue())
  await body(page).fill('保存失败也不能丢失的草稿')
  await page.getByRole('button', { name: '下一章', exact: true }).click()
  await expect(page.locator('.save-status')).toHaveText('保存失败')
  await expect(title(page)).toHaveValue('第 1 章')
  await expect(body(page)).toHaveText('保存失败也不能丢失的草稿')
  await page.unroute('**/api/chapters/*')
  await page.getByRole('button', { name: '重试保存' }).click()
  await saved(page)
  await page.getByRole('button', { name: '下一章', exact: true }).click()
  await expect(title(page)).toHaveValue('第 2 章')
})

test('focus mode, scoped shortcuts and Escape retain document and browser bindings', async ({ page }) => {
  await start(page, '快捷键与专注', true)
  await page.clock.install()
  await body(page).fill('快捷键正文')
  // Dispatch cancelable keys to inspect preventDefault without opening browser dialogs.
  const nativeSave = await body(page).evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 's', code: 'KeyS', ctrlKey: true, bubbles: true, cancelable: true })))
  expect(nativeSave).toBe(true)
  await expect(page.locator('.save-status')).toHaveText('未保存 · 等待自动保存')
  const composing = await body(page).evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'f', code: 'KeyF', ctrlKey: true, altKey: true, shiftKey: true, isComposing: true, bubbles: true, cancelable: true })))
  expect(composing).toBe(true)
  await expect(page.getByRole('button', { name: '专注写作', exact: true })).toBeVisible()
  await body(page).press('ControlOrMeta+Alt+Shift+s')
  await saved(page)
  await body(page).press('ControlOrMeta+Alt+Shift+f')
  await expect(page.getByRole('navigation', { name: '小说列表' })).not.toBeVisible()
  await expect(page.getByRole('group', { name: '正文格式' })).not.toBeVisible()
  await expect(page.getByRole('button', { name: '小说设置', exact: true })).not.toBeVisible()
  await expect(page.getByRole('button', { name: '立即保存' })).toBeVisible()
  await body(page).press('ControlOrMeta+Alt+Shift+ArrowDown')
  await expect(title(page)).toHaveValue('第 2 章')
  await body(page).press('Escape')
  await expect(page.getByRole('navigation', { name: '小说列表' })).toBeVisible()
  await expect(page.getByRole('group', { name: '正文格式' })).toBeVisible()
  await body(page).press('ControlOrMeta+Alt+Shift+ArrowUp')
  await expect(body(page)).toHaveText('快捷键正文')
  await page.getByRole('button', { name: '小说设置', exact: true }).click()
  await page.getByRole('dialog').getByLabel('小说名称').press('ControlOrMeta+Alt+Shift+f')
  await expect(page.locator('.workspace')).not.toHaveClass(/focused/)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
})

test('long prose keeps the contenteditable node, scroll and selection while saving', async ({ page }) => {
  await start(page, '长篇正文')
  const text = '长篇正文 hello world 123。'.repeat(1500)
  await body(page).fill(text)
  await expect(page.getByLabel('字数统计')).toHaveText('10500 字')
  await saved(page)
  const original = await body(page).elementHandle()
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/chapters/*', async route => {
    if (route.request().method() === 'PUT') await gate
    await route.continue()
  })
  try {
    await body(page).press('ControlOrMeta+End')
    await body(page).press('End')
    await page.keyboard.insertText('字')
    await expect(page.getByLabel('字数统计')).toHaveText('10501 字')
    // Wait for the real request and normal caret scrolling before measuring.
    // Only the completion of autosave is allowed to change after this snapshot.
    await expect(page.locator('.save-status')).toHaveText('保存中…')
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    const before = await page.locator('.document').evaluate(element => element.scrollTop)
    release()
    await saved(page)
    expect(await body(page).evaluate((element, previous) => element === previous, original)).toBe(true)
    expect(await page.locator('.document').evaluate(element => element.scrollTop)).toBe(before)
  } finally { release(); await page.unroute('**/api/chapters/*') }
  await page.getByRole('button', { name: '刷新本地数据' }).click()
  await expect(page.getByLabel('字数统计')).toHaveText('10501 字')
  await expect(body(page)).toContainText(text)
})

test('writing shortcuts stay in writing while profile drafts keep module navigation blocked', async ({ page }) => {
  await start(page, '模块整合', true)
  await body(page).fill('整合测试 Hello')
  await saved(page)
  const modules = page.getByRole('navigation', { name: '小说工作台模块' })
  await modules.getByRole('button', { name: '人物档案', exact: true }).click()
  await page.getByRole('button', { name: '新增人物', exact: true }).first().click()
  await expect(page.locator('.profile-save-status')).toHaveText('已保存到数据库')
  await page.route('**/api/novels/*/characters/*', route => route.request().method() === 'PUT' ? route.abort('failed') : route.continue())
  const name = page.getByLabel('姓名', { exact: true })
  await name.fill('联合角色')
  await expect(page.locator('.profile-save-status')).toHaveText('保存失败')
  await expect(modules.getByRole('button', { name: '章节写作', exact: true })).toBeDisabled()
  await expect(modules.getByRole('button', { name: '世界观', exact: true })).toBeDisabled()
  let chapterReads = 0
  page.on('request', request => { if (request.method() === 'GET' && /\/api\/chapters\//.test(request.url())) chapterReads++ })
  await name.press('ControlOrMeta+Alt+Shift+f')
  await name.press('ControlOrMeta+Alt+Shift+ArrowDown')
  await expect(page.locator('.workspace')).not.toHaveClass(/focused/)
  await expect(page.getByRole('button', { name: '专注写作', exact: true })).toBeDisabled()
  await expect(name).toHaveValue('联合角色')
  expect(chapterReads).toBe(0)
  await page.unroute('**/api/novels/*/characters/*')
  await page.getByRole('button', { name: '重试保存', exact: true }).click()
  await expect(page.locator('.profile-save-status')).toHaveText('已保存到数据库')
  await modules.getByRole('button', { name: '世界观', exact: true }).click()
  await expect(page.getByText('为故事构建一个世界')).toBeVisible()
  await modules.getByRole('button', { name: '章节写作', exact: true }).click()
  await expectChapterReady(page, '第 1 章', '整合测试 Hello')
  await expect(page.getByLabel('字数统计')).toHaveText('5 字')
  await page.getByRole('button', { name: '专注写作', exact: true }).click()
  await expect(modules).not.toBeVisible()
  await body(page).press('Escape')
  await expect(modules).toBeVisible()
})
